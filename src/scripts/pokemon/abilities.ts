export interface AbilityOption {
  name: string;
  hidden: boolean;
}

// Picks the most useful ability this Pokémon can actually have. Abilities the
// engine doesn't know are only used as a last resort.
export function pickAbility(options: AbilityOption[]): { name: string; desc: string } {
  let best: { name: string; desc: string; score: number } | null = null;
  for (const o of options) {
    const info = ABILITIES[o.name];
    const score = info ? info.score : -1;
    if (!best || score > best.score) best = { name: o.name, desc: info?.desc ?? NO_EFFECT, score };
  }
  return best ?? { name: "none", desc: NO_EFFECT };
}
